import { spawnSync } from 'node:child_process'
import { closeSync, existsSync, mkdirSync, openSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

function documentFiles(directory) {
  return existsSync(directory) ? readdirSync(directory).filter((name) => /^\d{4}-\d{4}-\d{2}-\d{2}-.+\.md$/.test(name)) : []
}

export function writePlanIndex(repositoryRoot) {
  const root = join(repositoryRoot, 'docs/superpowers')
  const entries = new Map()
  for (const section of ['specs', 'plans']) {
    for (const name of documentFiles(join(root, section))) {
      const id = name.slice(0, 4)
      const entry = entries.get(id) ?? { id, date: name.slice(5, 15) }
      entry[section] = name
      entries.set(id, entry)
    }
  }
  const rows = [...entries.values()]
    .sort((left, right) => left.id.localeCompare(right.id))
    .map((entry) => {
      const label = entry.plans ?? entry.specs
      const topic = label.slice(16).replace(/(?:-design)?\.md$/, '')
      const spec = entry.specs ? `[Specification](specs/${entry.specs})` : '—'
      const plan = entry.plans ? `[Plan](plans/${entry.plans})` : '—'
      return `| ${entry.id} | ${entry.date} | ${topic} | ${spec} | ${plan} |`
    })
  writeFileSync(
    join(root, 'README.md'),
    [
      '# Specifications and plans',
      '',
      'Generated by `npm run docs:new`. IDs are global and shared by each specification/plan pair.',
      '',
      '| ID | Date | Topic | Specification | Implementation |',
      '|---|---|---|---|---|',
      ...rows,
      '',
    ].join('\n'),
  )
}

export function createPlanDocuments(repositoryRoot, topic, date = new Date().toISOString().slice(0, 10)) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(topic ?? '')) throw new Error('Topic must be a lowercase kebab-case slug')
  const parsed = new Date(`${date}T00:00:00Z`)
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || !Number.isFinite(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== date)
    throw new Error('Invalid document date')
  const root = join(repositoryRoot, 'docs/superpowers')
  mkdirSync(root, { recursive: true })
  const lockPath = join(root, '.new-plan.lock')
  const lock = openSync(lockPath, 'wx')
  try {
    const names = ['specs', 'plans'].flatMap((section) => documentFiles(join(root, section)))
    const next = Math.max(0, ...names.map((name) => Number(name.slice(0, 4)))) + 1
    if (next > 9999) throw new Error('The four-digit document sequence is exhausted')
    const id = String(next).padStart(4, '0')
    const base = `${id}-${date}-${topic}`
    const specPath = join(root, 'specs', `${base}-design.md`)
    const planPath = join(root, 'plans', `${base}.md`)
    mkdirSync(dirname(specPath), { recursive: true })
    mkdirSync(dirname(planPath), { recursive: true })
    const title = topic
      .split('-')
      .map((word) => word[0].toUpperCase() + word.slice(1))
      .join(' ')
    writeFileSync(
      specPath,
      `# ${id} — ${title}\n\nStatus: Draft.\nDate: ${date}.\n\n## Intent\n\n## Scope and constraints\n\n## Design\n\n## Verification\n`,
      { flag: 'wx' },
    )
    try {
      writeFileSync(
        planPath,
        `# ${id} — ${title} Implementation Plan\n\nStatus: Draft.\n\n**Spec:** \`docs/superpowers/specs/${base}-design.md\`.\n\n## Tasks\n\n- [ ] Define behavior and regression tests.\n- [ ] Implement and verify the agreed scope.\n- [ ] Run project checks and record limitations.\n- [ ] Create an English Conventional Commit for this completed plan.\n`,
        { flag: 'wx' },
      )
    } catch (error) {
      unlinkSync(specPath)
      throw error
    }
    writePlanIndex(repositoryRoot)
    return { id, specPath, planPath }
  } finally {
    closeSync(lock)
    unlinkSync(lockPath)
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.length !== 3) throw new Error('Usage: npm run docs:new -- topic-slug')
    const result = createPlanDocuments(resolve(dirname(fileURLToPath(import.meta.url)), '..'), process.argv[2])
    const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
    const formatted = spawnSync(
      process.execPath,
      [join(repositoryRoot, 'node_modules/@biomejs/biome/bin/biome'), 'format', '--write', result.specPath, result.planPath],
      { cwd: repositoryRoot, stdio: 'inherit' },
    )
    if (formatted.status !== 0) throw new Error('Documents were created, but formatting failed')
    console.log(`${result.specPath}\n${result.planPath}`)
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
